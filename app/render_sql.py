"""Write the generated SQL to sql/*.sql for review or for running by hand.

    python -m app.render_sql

The files are generated from table_mapping.yaml; edit the YAML, not the SQL.
"""
from __future__ import annotations

import sys

from app.config import PROJECT_ROOT, ConfigError, load_settings
from app.schema import (
    Statement,
    create_tables,
    create_triggers,
    drop_triggers,
    report_queries,
    service_user_statements,
)

SQL_DIR = PROJECT_ROOT / "sql"
HEADER = "-- Generated by `python -m app.render_sql` from table_mapping.yaml. Do not edit by hand.\n"


def _render(title: str, notes: str, statements: list[Statement]) -> str:
    out = [HEADER, f"-- {title}\n"]
    out += [f"-- {line}\n" if line else "--\n" for line in notes.strip().splitlines()]
    uses_delimiter = any(s.is_routine for s in statements)
    if uses_delimiter:
        out.append("\nDELIMITER $$\n")
    for s in statements:
        end = "$$" if uses_delimiter else ";"
        out.append(f"\n-- {s.title}\n{s.sql}{end}\n")
    if uses_delimiter:
        out.append("\nDELIMITER ;\n")
    return "".join(out)


def main() -> int:
    try:
        settings = load_settings()
    except ConfigError as exc:
        print(exc, file=sys.stderr)
        return 1
    m = settings.mapping

    files = {
        "01_tables.sql": _render(
            "Queue and opt-in tables. Safe to re-run: existing tables and rows are kept.",
            "", create_tables(m)),
        "02_triggers.sql": _render(
            f"Triggers on {m.source['table']}. Safe to re-run (drops and re-creates them).",
            "Run 01_tables.sql first. The triggers run as the login that creates them:\n"
            "never delete that login while the triggers exist.",
            create_triggers(m)),
        "report.sql": _render(
            "Monitoring queries. Times are UTC.", "", report_queries(m)),
        "uninstall.sql": _render(
            "Remove the service from the database.",
            "Drops the triggers first, so the hospital table never references a missing table.\n"
            "The tables are kept (they hold the message history). To delete them too,\n"
            "run these by hand AFTER this script has dropped the triggers:\n"
            f"\n"
            f"  DROP TABLE IF EXISTS `{m.queue['table']}`;\n"
            f"  DROP TABLE IF EXISTS `{m.queue['optin_table']}`;",
            drop_triggers(m)),
        "optional_service_user.sql": _render(
            "OPTIONAL restricted login for the worker. Not used by setup.",
            "Replace CHANGE_ME, run as an admin, then put this login in .env.\n"
            "The triggers do not need it: they run as the login that created them.",
            service_user_statements(m, settings.db.name)),
    }

    SQL_DIR.mkdir(exist_ok=True)
    for name, text in files.items():
        (SQL_DIR / name).write_text(text, encoding="utf-8")
        print(f"wrote sql/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
